# Device configuration for Galaxy M21s / Galaxy F41 (Exynos 9611) (m21s).
# The Samsung model is SM-F415F; the community kernel calls this board f41.
TARGET_NAME="Galaxy M21s"
TARGET_CODENAME="m21s"
TARGET_ASSERT_MODEL=("SM-F415F" "SM-F415F/DS")
TARGET_PLATFORM="exynos9611"

# F415FUBS3CWK2 is the latest ZTO Android 12 release currently catalogued.
# The third component is only the FUS device identifier/TAC used by samloader;
# replace it with the phone's own IMEI/TAC if Samsung FUS rejects the default.
TARGET_FIRMWARE_DEVICE_ID="${TARGET_FIRMWARE_DEVICE_ID:-35209900}"
TARGET_FIRMWARE="SM-F415F/ZTO/$TARGET_FIRMWARE_DEVICE_ID"
TARGET_FIRMWARE_VERSION="F415FUBS3CWK2/F415FOWO3CWK2/F415FDDS3CWK2"
TARGET_EXTRA_FIRMWARES=()
TARGET_PLATFORM_SDK_VERSION=31

# Galaxy F41/M21 uses the values from the extracted F415F ZTO metadata. The
# The stock group is too small for the Android 17 ext4 port. The temporary
# repartitioner under platform/exynos9611/installer/repartitioner_m21s grows
# physical super to 11305 MiB (11301 MiB usable group space, including the
# configured 256-MiB ext4 margin). Keep the build-side values in sync with
# that layout; a stock PIT will not provide this capacity.
