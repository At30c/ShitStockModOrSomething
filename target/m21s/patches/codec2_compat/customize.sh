#!/usr/bin/env bash

SKIPUNZIP=1

if [[ "$SOURCE_PLATFORM_SDK_VERSION" -lt 36 ]]; then
    LOG "- Source is not Android 16; skipping Codec2 APV compatibility"
    return 0
fi

# Android 17 enables APV in media.swcodec based on the platform SDK even when
# its XML entries carry enabled="false". Both APV factories then probe a 4x4
# GraphicBuffer using pixel format 0x2b. The M21s Mali-G72 gralloc does not
# implement that format, so every MediaCodecList rebuild produces allocation
# failures. APV is not supported by this target; remove only its two component
# libraries and catalogue entries while retaining all legacy software codecs.
SWCODEC_CAPEX="$WORK_DIR/system/system/apex/com.google.android.media.swcodec_compressed.apex"
SWCODEC_TMP="$TMP_DIR/m21s_swcodec_compat"
SWCODEC_DECODED="$SWCODEC_TMP/decoded"
SWCODEC_CAPEX_DECODED="$SWCODEC_TMP/capex-decoded"
SWCODEC_PAYLOAD="$SWCODEC_DECODED/unknown/apex_payload"
SWCODEC_SOURCE_FIRMWARE_PATH="$(cut -d "/" -f 1 <<< "$SOURCE_FIRMWARE")_$(cut -d "/" -f 2 <<< "$SOURCE_FIRMWARE")"
SWCODEC_SOURCE_CAPEX="$FW_DIR/$SWCODEC_SOURCE_FIRMWARE_PATH/system/system/apex/com.google.android.media.swcodec_compressed.apex"

if [ ! -f "$SWCODEC_CAPEX" ]; then
    LOGE "media.swcodec CAPEX not found: ${SWCODEC_CAPEX//$WORK_DIR/}"
    return 1
fi

if ! sudo -n -v &> /dev/null; then
    LOG "\033[0;33m! Root permissions are required to unpack media.swcodec\033[0m"
    if ! sudo -v 2> /dev/null; then
        LOGE "Root permissions are required to unpack media.swcodec"
        return 1
    fi
fi

if mountpoint -q "$SWCODEC_TMP/mnt"; then
    LOGW "Unmounting stale media.swcodec payload from a previous build"
    sudo umount "$SWCODEC_TMP/mnt" || return 1
fi
rm -rf "$SWCODEC_TMP"
mkdir -p "$SWCODEC_TMP"

LOG "- Extracting media.swcodec APEX"
if unzip -l "$SWCODEC_CAPEX" original_apex 2> /dev/null | grep -q original_apex; then
    cp -a "$SWCODEC_CAPEX" "$SWCODEC_TMP/original.capex"
    unzip -p "$SWCODEC_CAPEX" original_apex > "$SWCODEC_TMP/original.apex"
else
    # Incremental work directories may already contain the uncompressed APEX
    # generated by an earlier module run. Use it as the inner APEX and recover
    # the compressed wrapper from the extracted source firmware.
    cp -a "$SWCODEC_CAPEX" "$SWCODEC_TMP/original.apex"
    if ! unzip -l "$SWCODEC_SOURCE_CAPEX" original_apex 2> /dev/null | \
            grep -q original_apex; then
        LOGE "Original media.swcodec CAPEX wrapper not found"
        return 1
    fi
    cp -a "$SWCODEC_SOURCE_CAPEX" "$SWCODEC_TMP/original.capex"
fi
EVAL "apktool d -j \"$(nproc)\" -o \"$SWCODEC_DECODED\" -r \"$SWCODEC_TMP/original.apex\""

mkdir -p "$SWCODEC_PAYLOAD" "$SWCODEC_TMP/mnt"
if ! sudo mount -o ro "$SWCODEC_DECODED/unknown/apex_payload.img" "$SWCODEC_TMP/mnt"; then
    LOGE "Failed to mount media.swcodec payload"
    return 1
fi
if ! sudo cp -a -T "$SWCODEC_TMP/mnt" "$SWCODEC_PAYLOAD" || \
        ! sudo chown -hR "$(whoami):$(whoami)" "$SWCODEC_PAYLOAD"; then
    sudo umount "$SWCODEC_TMP/mnt" || true
    LOGE "Failed to extract media.swcodec payload"
    return 1
fi
rm -rf "$SWCODEC_PAYLOAD/lost+found"

if ! sudo find "$SWCODEC_TMP/mnt" \
        -exec stat -c "%n %u %g %a capabilities=0x0" "{}" \; \
        > "$SWCODEC_TMP/fs_config" || \
        ! sudo find "$SWCODEC_TMP/mnt" -exec sh -c '
            for path do
                label="$(getfattr -n security.selinux --only-values -h --absolute-names "$path")" || exit 1
                printf "%s %s\n" "$path" "$label"
            done
        ' sh "{}" + > "$SWCODEC_TMP/file_contexts"; then
    sudo umount "$SWCODEC_TMP/mnt" || true
    LOGE "Failed to record media.swcodec filesystem metadata"
    return 1
fi
sudo umount "$SWCODEC_TMP/mnt" || return 1
rm -rf "$SWCODEC_TMP/mnt" "$SWCODEC_DECODED/unknown/apex_payload.img"

sort -o "$SWCODEC_TMP/file_contexts" "$SWCODEC_TMP/file_contexts"
sort -o "$SWCODEC_TMP/fs_config" "$SWCODEC_TMP/fs_config"
sed -i -e "s|$SWCODEC_TMP/mnt |/ |g" -e "s|$SWCODEC_TMP/mnt||g" "$SWCODEC_TMP/file_contexts"
sed -i -e 's|\.|\\.|g' -e 's|+|\\+|g' -e 's|\[|\\[|g' \
    -e 's|\]|\\]|g' -e 's|\*|\\*|g' "$SWCODEC_TMP/file_contexts"
sed -i -e "s|$SWCODEC_TMP/mnt | |g" -e "s|$SWCODEC_TMP/mnt/||g" "$SWCODEC_TMP/fs_config"

# Android 17's imported Codec2 store still contains the APV loader names even
# after the catalogue and AConfig values are disabled. On this target that
# makes media.swcodec abort while trying to dlopen the removed libraries. The
# equal-length replacements below keep the loader pointed at existing
# software codecs, while the exported APV support query returns false. Apply
# the same guard to the copies in /system: media.swcodec's linker namespace
# can resolve libcodec2_vndk.so from there instead of the APEX copy.
PATCH_APV_FLAG_ELF() {
    local file="$1"

    [ -f "$file" ] || return 0
    for symbol in \
            android_media_swcodec_flags_apv_software_codec \
            android_media_swcodec_flags_apv_software_codec_cq; do
        local address
        address="$(readelf -Ws "$file" 2>/dev/null | awk -v symbol="$symbol" '$4 == "FUNC" && $7 != "UND" && $8 == symbol { print $2; exit }')"
        [ -n "$address" ] || continue
        local offset=$((16#$address))
        python3 - "$file" "$offset" <<'PY_APV_FLAG'
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
offset = int(sys.argv[2])
patch = bytes.fromhex("00 00 80 52 c0 03 5f d6")
data = bytearray(path.read_bytes())
if data[offset:offset + len(patch)] != patch:
    data[offset:offset + len(patch)] = patch
path.write_bytes(data)
PY_APV_FLAG
    done
}

PATCH_APV_ELF() {
    local file="$1"
    local abi="$2"

    [ -f "$file" ] || return 0
    if ! strings "$file" | grep -q 'libcodec2_soft_apv'; then
        return 0
    fi

    python3 - "$file" <<'PY_APV_NAMES'
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
data = path.read_bytes()
replacements = (
    (b"libcodec2_soft_apvdec.so", b"libcodec2_soft_rawdec.so"),
    (b"libcodec2_soft_apvenc.so", b"libcodec2_soft_avcenc.so"),
)
for old, new in replacements:
    count = data.count(old)
    if count:
        if len(old) != len(new):
            raise SystemExit(f"APV replacement length mismatch in {path}")
        data = data.replace(old, new)
path.write_bytes(data)
PY_APV_NAMES

    local support_addr
    support_addr="$(readelf -Ws "$file" 2>/dev/null | awk '$4 == "FUNC" && $7 != "UND" && $8 == "android_media_codec_apv_support" { print $2; exit }')"
    if [ -z "$support_addr" ]; then
        LOGE "APV support symbol is missing from ${file//$WORK_DIR/}"
        return 1
    fi

    local support_offset=$((16#$support_addr))
    local support_bytes="00 00 80 52 c0 03 5f d6"
    if [ "$abi" = "32" ]; then
        # ELF32 exports Thumb symbols with bit 0 set. movs r0,#0; bx lr.
        support_offset=$((support_offset & ~1))
        support_bytes="00 20 70 47"
    fi
    python3 - "$file" "$support_offset" "$support_bytes" <<'PY_APV_CODE'
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
offset = int(sys.argv[2])
patch = bytes.fromhex(sys.argv[3])
data = bytearray(path.read_bytes())
if data[offset:offset + len(patch)] != patch:
    data[offset:offset + len(patch)] = patch
path.write_bytes(data)
PY_APV_CODE
}

SWCODEC_XML="$SWCODEC_PAYLOAD/etc/media_codecs.xml"
if [ ! -f "$SWCODEC_XML" ]; then
    LOGE "Unexpected media.swcodec APV layout"
    return 1
fi

if grep -q 'c2\.android\.apv' "$SWCODEC_XML" || \
        [ -e "$SWCODEC_PAYLOAD/lib64/libcodec2_soft_apvdec.so" ] || \
        [ -e "$SWCODEC_PAYLOAD/lib64/libcodec2_soft_apvenc.so" ]; then
    LOG "- Disabling unsupported APV software codecs on legacy gralloc"
    # Treat XML-only, library-only, and half-applied states identically. A
    # failed incremental build can leave one APV .so removed before apktool
    # exits; requiring all three objects here would turn that recoverable state
    # into the misleading \"Inconsistent media.swcodec APV state\" abort.
    perl -0pi -e 's|\n\s*<MediaCodec name="c2\.android\.apv\.decoder".*?</MediaCodec>||s; s|\n\s*<MediaCodec name="c2\.android\.apv\.encoder".*?</MediaCodec>||s' "$SWCODEC_XML"
    rm -f "$SWCODEC_PAYLOAD/lib64/libcodec2_soft_apvdec.so" \
        "$SWCODEC_PAYLOAD/lib64/libcodec2_soft_apvenc.so"
    sed -i '/libcodec2_soft_apvdec/d; /libcodec2_soft_apvenc/d' \
        "$SWCODEC_TMP/fs_config" "$SWCODEC_TMP/file_contexts"
else
    LOG "- Unsupported APV software codecs are already disabled"
fi

PATCH_APV_ELF "$SWCODEC_PAYLOAD/lib64/libcodec2_vndk.so" "64"
PATCH_APV_ELF "$WORK_DIR/system/system/lib64/libcodec2_vndk.so" "64"
PATCH_APV_ELF "$WORK_DIR/system/system/lib/libcodec2_vndk.so" "32"
PATCH_APV_FLAG_ELF "$SWCODEC_PAYLOAD/lib64/android.media.swcodec.flags-aconfig-cc.so"

# The AConfig storage keeps one byte per flag ID.  IDs 1 and 2 are the two
# APV flags in this package; clear both values while retaining the map and
# metadata required by the generated flag library.
SWCODEC_FLAG_VAL="$SWCODEC_PAYLOAD/etc/flag.val"
if [ ! -f "$SWCODEC_FLAG_VAL" ]; then
    LOGE "media.swcodec AConfig values are missing"
    return 1
fi
python3 - "$SWCODEC_FLAG_VAL" <<'PY_APV_VALUES'
import pathlib
import sys

path = pathlib.Path(sys.argv[1])
data = bytearray(path.read_bytes())
if len(data) <= 0x30:
    raise SystemExit(f"short AConfig value file: {path}")
data[0x2f] = 0
data[0x30] = 0
path.write_bytes(data)
PY_APV_VALUES

if grep -q 'c2\.android\.apv' "$SWCODEC_XML" || \
        [ -e "$SWCODEC_PAYLOAD/lib64/libcodec2_soft_apvdec.so" ] || \
        [ -e "$SWCODEC_PAYLOAD/lib64/libcodec2_soft_apvenc.so" ]; then
    LOGE "media.swcodec APV removal validation failed"
    return 1
fi
for CODEC2_APV_ELF in \
        "$SWCODEC_PAYLOAD/lib64/libcodec2_vndk.so" \
        "$WORK_DIR/system/system/lib64/libcodec2_vndk.so" \
        "$WORK_DIR/system/system/lib/libcodec2_vndk.so"; do
    if [ -f "$CODEC2_APV_ELF" ] && strings "$CODEC2_APV_ELF" | grep -q 'libcodec2_soft_apv'; then
        LOGE "APV loader name remains in ${CODEC2_APV_ELF//$WORK_DIR/}"
        return 1
    fi
done
python3 - "$SWCODEC_FLAG_VAL" <<'PY_APV_VALIDATE'
import pathlib
import sys

data = pathlib.Path(sys.argv[1]).read_bytes()
if len(data) <= 0x30 or data[0x2f] != 0 or data[0x30] != 0:
    raise SystemExit("APV AConfig values are not disabled")
PY_APV_VALIDATE

LOG "- Rebuilding media.swcodec apex_payload.img"
"$SRC_DIR/scripts/build_fs_image.sh" "ext4" --no-avb \
    -o "$SWCODEC_DECODED/unknown/apex_payload.img" -p "system" \
    "$SWCODEC_PAYLOAD" "$SWCODEC_TMP/file_contexts" "$SWCODEC_TMP/fs_config" > /dev/null
rm -rf "$SWCODEC_PAYLOAD" "$SWCODEC_TMP/file_contexts" "$SWCODEC_TMP/fs_config"

SWCODEC_SALT="$(sha256sum "$SWCODEC_DECODED/unknown/apex_manifest.pb" | cut -d ' ' -f 1)"
EVAL "avbtool add_hashtree_footer --do_not_generate_fec --algorithm \"SHA256_RSA4096\" --hash_algorithm \"sha256\" --key \"$SRC_DIR/security/avb/testkey_rsa4096.pem\" --prop \"apex.key:com.android.media.swcodec\" --salt \"$SWCODEC_SALT\" --image \"$SWCODEC_DECODED/unknown/apex_payload.img\""
EVAL "avbtool extract_public_key --key \"$SRC_DIR/security/avb/testkey_rsa4096.pem\" --output \"$SWCODEC_DECODED/unknown/apex_pubkey\""

mkdir -p "$SWCODEC_DECODED/build/apk"
cp -a "$SWCODEC_DECODED/original/META-INF" "$SWCODEC_DECODED/build/apk/META-INF"
EVAL "apktool b -j \"$(nproc)\" \"$SWCODEC_DECODED\""
SWCODEC_BUILT="$SWCODEC_DECODED/dist/original.apex"
if [ ! -f "$SWCODEC_BUILT" ]; then
    LOGE "Rebuilt media.swcodec APEX not found"
    return 1
fi

SWCODEC_CERT_PREFIX="aosp"
if $ROM_IS_OFFICIAL; then
    SWCODEC_CERT_PREFIX="unica"
fi
EVAL "signapk -a 4096 --align-file-size \"$SRC_DIR/security/${SWCODEC_CERT_PREFIX}_platform.x509.pem\" \"$SRC_DIR/security/${SWCODEC_CERT_PREFIX}_platform.pk8\" \"$SWCODEC_BUILT\" \"$SWCODEC_BUILT.signed\""

# Keep media.swcodec compressed. The M21s system partition has little spare
# space and cannot carry the 36 MiB uncompressed APEX in place of its 16 MiB
# CAPEX. Reuse the source wrapper metadata, replace only original_apex and its
# payload public key, then sign the outer container again.
LOG "- Rebuilding compressed media.swcodec CAPEX"
EVAL "apktool d -j \"$(nproc)\" -o \"$SWCODEC_CAPEX_DECODED\" -r \"$SWCODEC_TMP/original.capex\""
cp -f "$SWCODEC_BUILT.signed" "$SWCODEC_CAPEX_DECODED/unknown/original_apex"
unzip -p "$SWCODEC_BUILT.signed" apex_pubkey > "$SWCODEC_CAPEX_DECODED/unknown/apex_pubkey"

# A CAPEX manifest records the AVB root digest of original_apex. Replacing the
# inner APEX without updating field 12 makes apexd reject the wrapper before
# media.swcodec can be activated. Both digests are fixed-width SHA-256 strings,
# so update the protobuf payload in place without changing its wire layout.
SWCODEC_OLD_ROOT_DIGEST="$(strings "$SWCODEC_CAPEX_DECODED/unknown/apex_manifest.pb" | \
    grep -o -E '[0-9a-f]{64}' | head -n 1)"
SWCODEC_NEW_ROOT_DIGEST="$("$TOOLS_DIR/bin/avbtool" info_image \
    --image "$SWCODEC_DECODED/unknown/apex_payload.img" | \
    awk '/Root Digest:/ { print $3; exit }')"
if [[ ! "$SWCODEC_OLD_ROOT_DIGEST" =~ ^[0-9a-f]{64}$ ]] || \
        [[ ! "$SWCODEC_NEW_ROOT_DIGEST" =~ ^[0-9a-f]{64}$ ]]; then
    LOGE "Failed to resolve media.swcodec CAPEX root digests"
    return 1
fi
if [ "$SWCODEC_OLD_ROOT_DIGEST" != "$SWCODEC_NEW_ROOT_DIGEST" ]; then
    HEX_PATCH "$SWCODEC_CAPEX_DECODED/unknown/apex_manifest.pb" \
        "$(printf '%s' "$SWCODEC_OLD_ROOT_DIGEST" | xxd -p -c 0)" \
        "$(printf '%s' "$SWCODEC_NEW_ROOT_DIGEST" | xxd -p -c 0)" \
        > /dev/null || return 1
fi
mkdir -p "$SWCODEC_CAPEX_DECODED/build/apk"
cp -a "$SWCODEC_CAPEX_DECODED/original/META-INF" "$SWCODEC_CAPEX_DECODED/build/apk/META-INF"
EVAL "apktool b -j \"$(nproc)\" \"$SWCODEC_CAPEX_DECODED\""
SWCODEC_CAPEX_BUILT="$SWCODEC_CAPEX_DECODED/dist/original.capex"
if [ ! -f "$SWCODEC_CAPEX_BUILT" ]; then
    LOGE "Rebuilt compressed media.swcodec CAPEX not found"
    return 1
fi
EVAL "signapk -a 4096 --align-file-size \"$SRC_DIR/security/${SWCODEC_CERT_PREFIX}_platform.x509.pem\" \"$SRC_DIR/security/${SWCODEC_CERT_PREFIX}_platform.pk8\" \"$SWCODEC_CAPEX_BUILT\" \"$SWCODEC_CAPEX_BUILT.signed\""
mv -f "$SWCODEC_CAPEX_BUILT.signed" "$SWCODEC_CAPEX"
rm -rf "$SWCODEC_TMP"

unset CODEC2_POLICY CODEC2_OLD_RULE CODEC2_NEW_RULE CODEC2_SYSCALL_RULE
unset CODEC2_APV_ELF SWCODEC_CAPEX SWCODEC_TMP SWCODEC_DECODED SWCODEC_CAPEX_DECODED \
    SWCODEC_PAYLOAD SWCODEC_SOURCE_FIRMWARE_PATH SWCODEC_SOURCE_CAPEX \
    SWCODEC_XML SWCODEC_FLAG_VAL SWCODEC_SALT \
    SWCODEC_BUILT SWCODEC_CAPEX_BUILT SWCODEC_CERT_PREFIX \
    SWCODEC_OLD_ROOT_DIGEST SWCODEC_NEW_ROOT_DIGEST
