::ndk::ScopedAStatus CameraDevice::open(
        const std::shared_ptr<aidl_device::ICameraDeviceCallback>& callback,
        std::shared_ptr<aidl_device::ICameraDeviceSession>* output) {
    if (output) output->reset();
    if (!output || !callback || !module_)
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_ARGUMENT);
    int error = 0;
    auto session = CameraSession::create(module_, cameraId_, publicId_, openId_, callback, &error);
    ALOGI("CameraDevice: open metadata_id=%d open_id=%s session=%p error=%d", cameraId_,
          openId_.c_str(), session.get(), error);
    if (!session) {
        // A factory fecha o camera3_device_t em qualquer falha posterior a
        // open(), portanto este retorno não deixa FIMC-IS sem proprietário.
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    }
    *output = std::move(session);
    return ::ndk::ScopedAStatus::ok();
}

