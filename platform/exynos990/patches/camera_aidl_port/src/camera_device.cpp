// Samsung Camera2 reads this vendor key for the PRIVATE preview surface. The
// native Exynos module already publishes the equivalent standard stream list,
// but its older provider wrapper used to mirror the list into this tag.
constexpr uint32_t kAvailablePreviewStreamConfigurations = 0x80040004u;
constexpr uint32_t kAvailableCapabilities = ANDROID_REQUEST_AVAILABLE_CAPABILITIES;
constexpr uint32_t kAvailableColorSpaceProfilesMap =
        ANDROID_REQUEST_AVAILABLE_COLOR_SPACE_PROFILES_MAP;
// Samsung's camera app reads these vendor tags for the logical lens slider.
// They are registered by the Exynos module, so hard-coding their IDs here is
// safe after Camera3Module installs the vendor tag table.
constexpr uint32_t kSamsungMaxDigitalZoom = 0x80040011u;
constexpr uint32_t kSamsungMinDigitalZoomList = 0x80040012u;
constexpr uint32_t kSamsungMaxDigitalZoomList = 0x80040013u;
constexpr int32_t kImplementationDefined = 34;  // HAL_PIXEL_FORMAT_IMPLEMENTATION_DEFINED
constexpr int32_t kJpeg = 33;                   // HAL_PIXEL_FORMAT_BLOB/JPEG
constexpr int32_t kOutput = 0;

bool minimalStreamMetadataForTest() {
    char value[PROP_VALUE_MAX] = {};
    const int length = __system_property_get("vendor.camera.aidl.minimal_streams", value);
    return length > 0 && std::strcmp(value, "1") == 0;
}

bool filterMinimalOutputConfigurations(camera_metadata_t* metadata, int cameraId) {
    if (!metadata) return false;
    camera_metadata_entry entry{};
    if (find_camera_metadata_entry(metadata,
                                   ANDROID_SCALER_AVAILABLE_STREAM_CONFIGURATIONS,
                                   &entry) != 0 || entry.type != TYPE_INT32 ||
        entry.count < 4 || (entry.count % 4) != 0) {
        return false;
    }
    std::vector<int32_t> filtered;
    filtered.reserve(entry.count);
    size_t originalOutputs = 0;
    size_t keptOutputs = 0;
    for (size_t index = 0; index + 3 < entry.count; index += 4) {
        const int32_t format = entry.data.i32[index];
        const int32_t direction = entry.data.i32[index + 3];
        if (direction == kOutput) ++originalOutputs;
        // The Exynos 990 HAL exposes preview and JPEG through m_enumStreamInfo.
        // YUV/RAW auxiliary streams are generated by the Samsung HIDL wrapper
        // and exceed this blob's three-stream manager when sent directly from
        // the AIDL Camera2 path. Keep input entries and only these two output
        // formats for the controlled compatibility run.
        const bool keep = direction != kOutput || format == kImplementationDefined ||
                format == kJpeg;
        if (keep) {
            filtered.insert(filtered.end(), entry.data.i32 + index,
                            entry.data.i32 + index + 4);
            if (direction == kOutput) ++keptOutputs;
        }
    }
    if (filtered.empty() || keptOutputs == 0 ||
        update_camera_metadata_entry(metadata, entry.index, filtered.data(), filtered.size(),
                                     nullptr) != 0) {
        ALOGE("CameraDevice: unable to filter minimal stream metadata id=%d", cameraId);
        return false;
    }
    ALOGI("CameraDevice: minimal stream metadata id=%d outputs=%zu->%zu", cameraId,
          originalOutputs, keptOutputs);
    return true;
}

bool buildPreviewConfigurations(const camera_metadata_t* source,
                                std::vector<int32_t>* configurations) {
    if (!source || !configurations) return false;
    camera_metadata_entry entry{};
    if (find_camera_metadata_entry(const_cast<camera_metadata_t*>(source),
                                   ANDROID_SCALER_AVAILABLE_STREAM_CONFIGURATIONS,
                                   &entry) != 0 || entry.type != TYPE_INT32 ||
        entry.count < 4 || (entry.count % 4) != 0) {
        return false;
    }
    configurations->clear();
    configurations->reserve(entry.count);
    for (size_t index = 0; index + 3 < entry.count; index += 4) {
        const int32_t format = entry.data.i32[index];
        const int32_t width = entry.data.i32[index + 1];
        const int32_t height = entry.data.i32[index + 2];
        const int32_t direction = entry.data.i32[index + 3];
        if (format != kImplementationDefined || direction != kOutput || width <= 0 || height <= 0)
            continue;
        configurations->insert(configurations->end(), {format, width, height, direction});
    }
    return !configurations->empty();
}

bool isRearLogicalCamera(int publicId) {
    return publicId == 20;
}

std::vector<uint8_t> rearLogicalPhysicalIds() {
    // Android encodes this tag as a sequence of NUL-terminated ASCII camera
    // IDs. These are the physical IDs declared by the y2s camera feature:
    // main (0), ultra-wide (2), tele-binning (50), tele-standard-crop (52).
    const char ids[] = "0\0" "2\0" "50\0" "52\0";
    return std::vector<uint8_t>(ids, ids + sizeof(ids) - 1);
}

int physicalBackendIdForLogicalId(int publicId, const std::string& physicalId) {
    if (publicId != 20) return -1;
    if (physicalId == "0") return 0;
    if (physicalId == "2") return 2;
    if (physicalId == "50") return 2;
    if (physicalId == "52") return 4;
    return -1;
}

// A libcamera_metadata da vendor (Android 11) não conhece tags do Android 13+,
// e add_camera_metadata_entry() recusa a inserção. O pacote é só copiado
// (copy_camera_metadata) e interpretado pela lib do cameraserver, que conhece
// a tag; por isso a entrada int32 é escrita direto no buffer, no layout
// camera_metadata v1 do AOSP. O layout é conferido contra a própria API
// antes de qualquer escrita, e a função desiste se algo divergir.
bool appendUnknownInt32Entry(camera_metadata_t* metadata, uint32_t tag, int32_t value) {
    struct Header {
        uint32_t size, version, flags, entryCount, entryCapacity, entriesStart;
        uint32_t dataCount, dataCapacity, dataStart, padding;
    };
    struct Entry {
        uint32_t tag, count;
        uint8_t data[4];
        uint8_t type, reserved[3];
    };
    static_assert(sizeof(Entry) == 16, "camera_metadata_buffer_entry v1");
    if (!metadata) return false;
    auto* header = reinterpret_cast<Header*>(metadata);
    if (header->version != 1 || header->size != get_camera_metadata_size(metadata) ||
        header->entryCount != get_camera_metadata_entry_count(metadata) ||
        header->entryCapacity != get_camera_metadata_entry_capacity(metadata) ||
        header->entryCount == 0 || header->entryCount >= header->entryCapacity) {
        return false;
    }
    auto* entries = reinterpret_cast<Entry*>(reinterpret_cast<uint8_t*>(metadata) +
                                             header->entriesStart);
    camera_metadata_entry first{};
    if (get_camera_metadata_entry(metadata, 0, &first) != 0 || entries[0].tag != first.tag ||
        entries[0].type != first.type || entries[0].count != first.count) {
        return false;
    }
    Entry& entry = entries[header->entryCount];
    entry = {};
    entry.tag = tag;
    entry.count = 1;
    std::memcpy(entry.data, &value, sizeof(value));
    entry.type = TYPE_INT32;
    ++header->entryCount;
    header->flags &= ~1u;  // FLAG_SORTED: a busca volta a ser linear.
    camera_metadata_entry check{};
    return find_camera_metadata_entry(metadata, tag, &check) == 0 && check.count == 1 &&
            check.data.i32[0] == value;
}

camera_metadata_t* makeSamsungCharacteristics(const camera_metadata_t* source, int cameraId,
                                              int publicId) {
    if (!source) return nullptr;
    // Só sintetiza a câmera lógica quando a metadata veio do backend físico;
    // get_camera_info(20) do próprio HAL já descreve os IDs físicos.
    const bool logicalRear = isRearLogicalCamera(publicId) && cameraId != publicId;
    const std::vector<uint8_t> physicalIds = logicalRear ? rearLogicalPhysicalIds() :
            std::vector<uint8_t>{};
    camera_metadata_entry existing{};
    const bool hasPreviewConfigurations =
            find_camera_metadata_entry(const_cast<camera_metadata_t*>(source),
                                       kAvailablePreviewStreamConfigurations, &existing) == 0;
    std::vector<int32_t> previewConfigurations;
    if (!hasPreviewConfigurations && !buildPreviewConfigurations(source, &previewConfigurations)) {
        ALOGI("CameraDevice: no PRIVATE output configurations to mirror id=%d", cameraId);
    }

    camera_metadata_entry capabilities{};
    const bool hasCapabilities =
            find_camera_metadata_entry(const_cast<camera_metadata_t*>(source),
                                       kAvailableCapabilities, &capabilities) == 0;
    bool hasColorSpaceCapability = false;
    if (hasCapabilities && capabilities.type == TYPE_BYTE) {
        for (size_t i = 0; i < capabilities.count; ++i) {
            if (capabilities.data.u8[i] ==
                    ANDROID_REQUEST_AVAILABLE_CAPABILITIES_COLOR_SPACE_PROFILES) {
                hasColorSpaceCapability = true;
                break;
            }
        }
    }
    camera_metadata_entry colorSpaceMap{};
    const bool hasColorSpaceMap =
            find_camera_metadata_entry(const_cast<camera_metadata_t*>(source),
                                       kAvailableColorSpaceProfilesMap, &colorSpaceMap) == 0;
    // Rebuild the capabilities entry even when the native blob appears to
    // contain value 20.  Older Samsung metadata tables can report that byte as
    // present while the compact packet delivered through AIDL drops it.
    const bool ensureColorSpaceCapability = true;
    const bool addColorSpaceCapability = !hasColorSpaceCapability;
    const bool addColorSpaceMap = !hasColorSpaceMap;
    // If an existing capabilities entry is present, replace it below instead
    // of resizing it in place.  Only a missing entry consumes another slot.
    // A logical rear camera needs physical IDs, sync type and the complete
    // zoom range used by Samsung Camera (0.5x through 30x). Reserve entries
    // for the two zoom tags even when the donor blob omitted them.
    // Sem as tags de intensidade o CameraService assume um único nível e o
    // controle de brilho da lanterna fica sem efeito. Ver kTorchStrength*.
    camera_metadata_entry flashEntry{};
    const bool hasFlash =
            find_camera_metadata_entry(const_cast<camera_metadata_t*>(source),
                                       ANDROID_FLASH_INFO_AVAILABLE, &flashEntry) == 0 &&
            flashEntry.type == TYPE_BYTE && flashEntry.count >= 1 &&
            flashEntry.data.u8[0] == ANDROID_FLASH_INFO_AVAILABLE_TRUE;
    const bool addTorchStrength = hasFlash &&
            find_camera_metadata_entry(const_cast<camera_metadata_t*>(source),
                                       ANDROID_FLASH_INFO_STRENGTH_MAXIMUM_LEVEL, &flashEntry) != 0;
    const size_t extraEntries = (hasPreviewConfigurations ? 0 : 1) +
            (!hasCapabilities ? (addColorSpaceCapability ? 1 : 0) : 0) +
            (addColorSpaceMap ? 1 : 0) + (logicalRear ? 4 : 0) + (addTorchStrength ? 2 : 0);
    const size_t colorSpaceMapDataSize = addColorSpaceMap ?
            calculate_camera_metadata_entry_data_size(TYPE_INT64, 3) : 0;
    const size_t entryCapacity = get_camera_metadata_entry_count(source) + extraEntries;
    const size_t dataCapacity = get_camera_metadata_data_count(source) +
            (hasPreviewConfigurations ? 0 :
             calculate_camera_metadata_entry_data_size(TYPE_INT32, previewConfigurations.size())) +
            (addColorSpaceCapability ? calculate_camera_metadata_entry_data_size(TYPE_BYTE, 1) : 0) +
            colorSpaceMapDataSize +
            (logicalRear ? calculate_camera_metadata_entry_data_size(TYPE_BYTE, physicalIds.size()) : 0) +
            (logicalRear ? calculate_camera_metadata_entry_data_size(TYPE_BYTE, 1) : 0) +
            (logicalRear ? calculate_camera_metadata_entry_data_size(TYPE_FLOAT, 2) : 0) +
            (logicalRear ? calculate_camera_metadata_entry_data_size(TYPE_FLOAT, 1) : 0);
    camera_metadata_t* result = allocate_camera_metadata(entryCapacity, dataCapacity);
    if (!result || append_camera_metadata(result, source) != 0 ||
        (!hasPreviewConfigurations && add_camera_metadata_entry(
                result, kAvailablePreviewStreamConfigurations, previewConfigurations.data(),
                previewConfigurations.size()) != 0)) {
        ALOGE("CameraDevice: failed to augment characteristics id=%d", cameraId);
        if (result) free_camera_metadata(result);
        return nullptr;
    }
    if (ensureColorSpaceCapability) {
        std::vector<uint8_t> capabilityValues;
        camera_metadata_entry current{};
        if (find_camera_metadata_entry(result, kAvailableCapabilities, &current) == 0 &&
            current.type == TYPE_BYTE) {
            capabilityValues.assign(current.data.u8, current.data.u8 + current.count);
        }
        if (std::find(capabilityValues.begin(), capabilityValues.end(),
                      static_cast<uint8_t>(ANDROID_REQUEST_AVAILABLE_CAPABILITIES_COLOR_SPACE_PROFILES)) ==
                capabilityValues.end()) {
            capabilityValues.push_back(
                    ANDROID_REQUEST_AVAILABLE_CAPABILITIES_COLOR_SPACE_PROFILES);
        }
        if (logicalRear &&
            std::find(capabilityValues.begin(), capabilityValues.end(),
                      static_cast<uint8_t>(ANDROID_REQUEST_AVAILABLE_CAPABILITIES_LOGICAL_MULTI_CAMERA)) ==
                capabilityValues.end()) {
            capabilityValues.push_back(
                    ANDROID_REQUEST_AVAILABLE_CAPABILITIES_LOGICAL_MULTI_CAMERA);
        }
        int status = 0;
        if (current.count != 0) {
            // Some Samsung camera_metadata implementations report success for
            // update_camera_metadata_entry() but retain the old byte count.
            // Delete and re-add the unique tag so the compact AIDL packet
            // definitely contains capability 20.
            status = delete_camera_metadata_entry(result, current.index);
            if (status == 0) {
                status = add_camera_metadata_entry(result, kAvailableCapabilities,
                                                   capabilityValues.data(),
                                                   capabilityValues.size());
            }
        } else {
            status = add_camera_metadata_entry(result, kAvailableCapabilities,
                                               capabilityValues.data(),
                                               capabilityValues.size());
        }
        if (status != 0) {
            ALOGE("CameraDevice: failed to update color-space capability id=%d status=%d",
                  cameraId, status);
            free_camera_metadata(result);
            return nullptr;
        }
    }
    if (addColorSpaceMap) {
        // Android's map is a sequence of (color-space, image-format,
        // dynamic-range-profile) int64 triples.  Exynos exposes the standard
        // implementation-defined preview path, so advertise only the
        // conservative sRGB/standard combination.
        const int64_t profile[3] = {ANDROID_REQUEST_AVAILABLE_COLOR_SPACE_PROFILES_MAP_SRGB,
                                    kImplementationDefined, 1};
        if (add_camera_metadata_entry(result, kAvailableColorSpaceProfilesMap, profile, 3) != 0) {
            // Some Samsung camera_metadata tables predate the Android 17
            // color-space map tag even though the AIDL provider ABI accepts
            // the corresponding capability.  Keep the valid characteristics
            // packet and omit only this optional map instead of rejecting the
            // whole camera, which makes CameraService report no camera at all.
            ALOGI("CameraDevice: color-space profile map unsupported by metadata table id=%d; omitted",
                  cameraId);
        }
    }
    if (addTorchStrength) {
        const int32_t maximumLevel = kTorchStrengthMaximumLevel;
        const int32_t defaultLevel = kTorchStrengthDefaultLevel;
        auto addLevel = [result](uint32_t tag, int32_t value) {
            return add_camera_metadata_entry(result, tag, &value, 1) == 0 ||
                    appendUnknownInt32Entry(result, tag, value);
        };
        if (!addLevel(ANDROID_FLASH_INFO_STRENGTH_MAXIMUM_LEVEL, maximumLevel) ||
            !addLevel(ANDROID_FLASH_INFO_STRENGTH_DEFAULT_LEVEL, defaultLevel)) {
            // Uma tag opcional não pode derrubar a câmera inteira.
            ALOGI("CameraDevice: torch strength tags not added id=%d", cameraId);
        }
    }
    if (logicalRear) {
        camera_metadata_entry physicalEntry{};
        if (find_camera_metadata_entry(result, ANDROID_LOGICAL_MULTI_CAMERA_PHYSICAL_IDS,
                                       &physicalEntry) == 0) {
            if (update_camera_metadata_entry(result, physicalEntry.index, physicalIds.data(),
                                             physicalIds.size(), nullptr) != 0) {
                ALOGE("CameraDevice: unable to update logical physical IDs id=%d", cameraId);
                free_camera_metadata(result);
                return nullptr;
            }
        } else if (add_camera_metadata_entry(result, ANDROID_LOGICAL_MULTI_CAMERA_PHYSICAL_IDS,
                                             physicalIds.data(), physicalIds.size()) != 0) {
            ALOGE("CameraDevice: unable to add logical physical IDs id=%d", cameraId);
            free_camera_metadata(result);
            return nullptr;
        }
        const uint8_t syncType = ANDROID_LOGICAL_MULTI_CAMERA_SENSOR_SYNC_TYPE_CALIBRATED;
        if (find_camera_metadata_entry(result, ANDROID_LOGICAL_MULTI_CAMERA_SENSOR_SYNC_TYPE,
                                       &physicalEntry) == 0) {
            if (update_camera_metadata_entry(result, physicalEntry.index, &syncType, 1, nullptr) != 0) {
                free_camera_metadata(result);
                return nullptr;
            }
        } else if (add_camera_metadata_entry(result, ANDROID_LOGICAL_MULTI_CAMERA_SENSOR_SYNC_TYPE,
                                             &syncType, 1) != 0) {
            free_camera_metadata(result);
            return nullptr;
        }
        const float zoomRange[2] = {0.5f, 30.0f};
        camera_metadata_entry zoomEntry{};
        if (find_camera_metadata_entry(result, ANDROID_CONTROL_ZOOM_RATIO_RANGE,
                                       &zoomEntry) == 0) {
            if (update_camera_metadata_entry(result, zoomEntry.index, zoomRange, 2, nullptr) != 0) {
                ALOGE("CameraDevice: unable to update logical zoom range id=%d", cameraId);
                free_camera_metadata(result);
                return nullptr;
            }
        } else if (add_camera_metadata_entry(result, ANDROID_CONTROL_ZOOM_RATIO_RANGE,
                                             zoomRange, 2) != 0) {
            ALOGE("CameraDevice: unable to add logical zoom range id=%d", cameraId);
            free_camera_metadata(result);
            return nullptr;
        }
        const float maxDigitalZoom = 30.0f;
        if (find_camera_metadata_entry(result, ANDROID_SCALER_AVAILABLE_MAX_DIGITAL_ZOOM,
                                       &zoomEntry) == 0) {
            if (update_camera_metadata_entry(result, zoomEntry.index, &maxDigitalZoom, 1,
                                             nullptr) != 0) {
                ALOGE("CameraDevice: unable to update logical max digital zoom id=%d", cameraId);
                free_camera_metadata(result);
                return nullptr;
            }
        } else if (add_camera_metadata_entry(result, ANDROID_SCALER_AVAILABLE_MAX_DIGITAL_ZOOM,
                                             &maxDigitalZoom, 1) != 0) {
            ALOGE("CameraDevice: unable to add logical max digital zoom id=%d", cameraId);
            free_camera_metadata(result);
            return nullptr;
        }
        // The Samsung Camera client uses the vendor list before it consults
        // the Android 11 zoomRatioRange.  Leaving the donor values (1..10)
        // here makes the UI clamp the logical camera to the old 1x/2x/3x
        // buttons even though the AIDL standard tags advertise 0.5..30.
        // Keep ten entries, matching the Exynos vendor contract, and expose
        // the same range for every logical lens slot. Physical cameras still
        // return their native vendor metadata through getPhysicalCameraCharacteristics().
        const float minDigitalZoomList[10] = {
                0.5f, 0.5f, 0.5f, 0.5f, 0.5f,
                0.5f, 0.5f, 0.5f, 0.5f, 0.5f};
        const float maxDigitalZoomList[10] = {
                30.0f, 30.0f, 30.0f, 30.0f, 30.0f,
                30.0f, 30.0f, 30.0f, 30.0f, 30.0f};
        camera_metadata_entry vendorZoom{};
        if (find_camera_metadata_entry(result, kSamsungMaxDigitalZoom, &vendorZoom) == 0 &&
            vendorZoom.type == TYPE_FLOAT) {
            if (update_camera_metadata_entry(result, vendorZoom.index, &maxDigitalZoom, 1,
                                             nullptr) != 0) {
                ALOGE("CameraDevice: unable to update Samsung max zoom id=%d", cameraId);
                free_camera_metadata(result);
                return nullptr;
            }
        }
        if (find_camera_metadata_entry(result, kSamsungMinDigitalZoomList, &vendorZoom) == 0 &&
            vendorZoom.type == TYPE_FLOAT) {
            if (update_camera_metadata_entry(result, vendorZoom.index, minDigitalZoomList, 10,
                                             nullptr) != 0) {
                ALOGE("CameraDevice: unable to update Samsung min zoom list id=%d", cameraId);
                free_camera_metadata(result);
                return nullptr;
            }
        }
        if (find_camera_metadata_entry(result, kSamsungMaxDigitalZoomList, &vendorZoom) == 0 &&
            vendorZoom.type == TYPE_FLOAT) {
            if (update_camera_metadata_entry(result, vendorZoom.index, maxDigitalZoomList, 10,
                                             nullptr) != 0) {
                ALOGE("CameraDevice: unable to update Samsung max zoom list id=%d", cameraId);
                free_camera_metadata(result);
                return nullptr;
            }
        }
        ALOGI("CameraDevice: logical rear metadata id=%d physicalIds=0,2,50,52 zoom=0.5..30.0",
              cameraId);
    }
    if (minimalStreamMetadataForTest()) {
        (void)filterMinimalOutputConfigurations(result, cameraId);
    }
    if (!hasPreviewConfigurations) {
        ALOGI("CameraDevice: mirrored %zu PRIVATE preview configurations id=%d",
              previewConfigurations.size() / 4, cameraId);
    }
    if (ensureColorSpaceCapability || addColorSpaceMap) {
        camera_metadata_entry verified{};
        int verifiedCount = -1;
        if (find_camera_metadata_entry(result, kAvailableCapabilities, &verified) == 0 &&
            verified.type == TYPE_BYTE) {
            verifiedCount = static_cast<int>(verified.count);
        }
        ALOGI("CameraDevice: Android 17 color-space metadata id=%d source_has_cap20=%d rebuilt=%d map=%d count=%d",
              cameraId, hasColorSpaceCapability, ensureColorSpaceCapability, addColorSpaceMap,
              verifiedCount);
    }
    return result;
}

