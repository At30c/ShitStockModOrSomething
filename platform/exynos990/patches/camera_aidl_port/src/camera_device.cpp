CameraDevice::CameraDevice(std::shared_ptr<Camera3Module> module, int cameraId, int publicId,
                           std::string openId)
    : module_(std::move(module)), cameraId_(cameraId), publicId_(publicId),
      openId_(std::move(openId)) {}

int CameraDevice::info(camera_info* output) const {
    return module_ ? module_->getCameraInfo(cameraId_, output) : -ENODEV;
}

::ndk::ScopedAStatus CameraDevice::unsupported(const char* operation) {
    return ::ndk::ScopedAStatus::fromExceptionCodeWithMessage(
            EX_UNSUPPORTED_OPERATION, operation);
}

::ndk::ScopedAStatus CameraDevice::getCameraCharacteristics(aidl_device::CameraMetadata* output) {
    ALOGI("CameraDevice: getCameraCharacteristics id=%d", cameraId_);
    if (!output) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_ARGUMENT);
    camera_info native{};
    if (info(&native) != 0 || !native.static_camera_characteristics) {
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    }
    // camera_metadata_t::size is the allocated capacity, not the serialized
    // payload length.  AIDL CameraMetadata must carry the compact payload;
    // copying the capacity appends unused bytes and can make the framework
    // discard StreamConfigurationMap entries (the Samsung app then gets a
    // null preview size and crashes).
    const size_t allocated = get_camera_metadata_size(native.static_camera_characteristics);
    camera_metadata_t* augmented = makeSamsungCharacteristics(
            native.static_camera_characteristics, cameraId_, publicId_);
    if (!augmented) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    const size_t size = get_camera_metadata_compact_size(augmented);
    ALOGI("CameraDevice: characteristics id=%d allocated=%zu compact=%zu", cameraId_, allocated,
          size);
    if (size == 0) {
        free_camera_metadata(augmented);
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    }
    output->metadata.resize(size);
    if (!copy_camera_metadata(output->metadata.data(), size,
                              augmented)) {
        free_camera_metadata(augmented);
        output->metadata.clear();
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    }
    free_camera_metadata(augmented);
    return ::ndk::ScopedAStatus::ok();
}

::ndk::ScopedAStatus CameraDevice::getPhysicalCameraCharacteristics(
        const std::string& physicalId, aidl_device::CameraMetadata* output) {
    ALOGI("CameraDevice: getPhysicalCameraCharacteristics id=%d physical=%s", cameraId_,
          physicalId.c_str());
    if (!output) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_ARGUMENT);
    output->metadata.clear();
    int backendId = -1;
    if (cameraId_ == publicId_ && nativeLogicalCameraIds()) {
        // SehCameraDevice::getPhysicalCameraCharacteristics() também usa atoi().
        if (!parseNumericCameraId(physicalId, &backendId)) backendId = -1;
    } else {
        backendId = physicalBackendIdForLogicalId(publicId_, physicalId);
    }
    if (backendId < 0 || !module_)
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_ARGUMENT);
    camera_info native{};
    if (module_->getCameraInfo(backendId, &native) != 0 ||
        !native.static_camera_characteristics)
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    camera_metadata_t* augmented = makeSamsungCharacteristics(
            native.static_camera_characteristics, backendId, -1);
    if (!augmented) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    const size_t size = get_camera_metadata_compact_size(augmented);
    output->metadata.resize(size);
    if (!copy_camera_metadata(output->metadata.data(), size, augmented)) {
        free_camera_metadata(augmented);
        output->metadata.clear();
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    }
    free_camera_metadata(augmented);
    return ::ndk::ScopedAStatus::ok();
}

::ndk::ScopedAStatus CameraDevice::getResourceCost(aidl_common::CameraResourceCost* output) {
    ALOGI("CameraDevice: getResourceCost id=%d", cameraId_);
    if (!output) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_ARGUMENT);
    camera_info native{};
    if (info(&native) != 0) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    output->resourceCost = native.resource_cost;
    output->conflictingDevices.clear();
    for (size_t index = 0; native.conflicting_devices && index < native.conflicting_devices_length;
         ++index) {
        if (native.conflicting_devices[index]) {
            // Camera3/HIDL exposes bare numeric IDs here.  AIDL's
            // CameraResourceCost requires the full device instance name so
            // CameraProviderManager can parse the conflict list.
            output->conflictingDevices.emplace_back(
                    "device@1.0/internal/" + std::string(native.conflicting_devices[index]));
        }
    }
    return ::ndk::ScopedAStatus::ok();
}

