::ndk::ScopedAStatus CameraDevice::setTorchMode(bool enabled) {
    ALOGI("CameraDevice: setTorchMode id=%d enabled=%d", cameraId_, enabled);
    if (!module_) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    const int result = module_->setTorchMode(std::to_string(cameraId_), enabled);
    return result == 0 ? ::ndk::ScopedAStatus::ok()
                       : ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
}

::ndk::ScopedAStatus CameraDevice::turnOnTorchWithStrengthLevel(int32_t strengthLevel) {
    // O SystemUI do Android 17 usa sempre esta entrada. O nível vai ao slot
    // Samsung set_torch_mode_strength do módulo, como no sehSetTorchModeStrength
    // do provider HIDL; a faixa 1..5 é a declarada nas características.
    ALOGI("CameraDevice: turnOnTorchWithStrengthLevel id=%d strength=%d", cameraId_,
          strengthLevel);
    if (strengthLevel < 1 || strengthLevel > kTorchStrengthMaximumLevel)
        return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_ARGUMENT);
    if (!module_) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
    const std::string id = std::to_string(cameraId_);
    int result = module_->setTorchModeStrength(id, strengthLevel);
    // Um módulo sem o slot Samsung mantém a lanterna binária.
    if (result == -ENOSYS) result = module_->setTorchMode(id, true);
    return result == 0 ? ::ndk::ScopedAStatus::ok()
                       : ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_STATE);
}

::ndk::ScopedAStatus CameraDevice::getTorchStrengthLevel(int32_t* output) {
    if (!output) return ::ndk::ScopedAStatus::fromExceptionCode(EX_ILLEGAL_ARGUMENT);
    *output = module_ ? module_->torchStrengthLevel(std::to_string(cameraId_))
                      : kTorchStrengthDefaultLevel;
    return ::ndk::ScopedAStatus::ok();
}

