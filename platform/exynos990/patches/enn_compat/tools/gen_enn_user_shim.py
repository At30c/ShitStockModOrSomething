#!/usr/bin/env python3
"""Generate the libenn_user_lib.so forwarding shim for the S24+ ENN.

App libraries live in the classloader namespace and only see the vendor
libraries listed in public.libraries.txt, and a symbol is looked up only in
their own DT_NEEDED entries: a shim that merely depends on the real library
does not make the real symbols visible.  So the shim must export every C
entry point itself.  Each one is a two-instruction tail jump through a
pointer table filled at load time from libenn_user_s24.so (the real S24+
library with its SONAME rewritten), which keeps any argument list intact.

Usage: gen_enn_user_shim.py <real libenn_user_lib.so> <output.S>
"""

import subprocess
import sys

MISSING = ["EnnExecuteModelWithSessionIdAndFlag"]


def exported_functions(lib):
    out = subprocess.run(["nm", "-D", "--defined-only", lib], check=True,
                         capture_output=True, text=True).stdout
    names = []
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] == "T" and not parts[2].startswith("_"):
            names.append(parts[2])
    return sorted(set(names))


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    names = [n for n in exported_functions(sys.argv[1]) if n not in MISSING]
    lines = [
        "/* Generated by gen_enn_user_shim.py; do not edit. */",
        "    .text",
    ]
    for i, name in enumerate(names):
        lines += [
            f"    .globl {name}",
            f"    .type {name}, %function",
            "    .p2align 2",
            f"{name}:",
            "    adrp x16, enn_shim_targets",
            "    add x16, x16, :lo12:enn_shim_targets",
            f"    ldr x16, [x16, #{i * 8}]",
            "    br x16",
            f"    .size {name}, .-{name}",
        ]
    lines += [
        "",
        "    .section .data.rel.ro,\"aw\"",
        "    .globl enn_shim_names",
        "    .hidden enn_shim_names",
        "    .p2align 3",
        "enn_shim_names:",
    ]
    lines += [f"    .xword .Lname{i}" for i in range(len(names))]
    lines += ["    .xword 0"]
    for i, name in enumerate(names):
        lines += [f".Lname{i}:", f'    .asciz "{name}"']
    lines += [
        "",
        "    .bss",
        "    .globl enn_shim_targets",
        "    .hidden enn_shim_targets",
        "    .p2align 3",
        "enn_shim_targets:",
        f"    .zero {len(names) * 8}",
        "    .globl enn_shim_count",
        "    .hidden enn_shim_count",
        "    .section .rodata",
        "    .p2align 2",
        "enn_shim_count:",
        f"    .word {len(names)}",
        "",
        '    .section .note.GNU-stack,"",%progbits',
    ]
    open(sys.argv[2], "w").write("\n".join(lines) + "\n")
    print(f"{len(names)} forwarded functions")


if __name__ == "__main__":
    main()
